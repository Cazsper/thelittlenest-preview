const SOURCE = {
  mode: 'zoho',             // 'local' | 'zoho' · see the warning above
};

/* Pages live at the root and in /products/ and /categories/, so asset paths
   are relative. Work out the prefix once from where this script was loaded. */
const PREFIX = (() => {
  const s = document.currentScript || [...document.scripts].pop();
  return (s?.src || '').replace(/assets\/js\/shop\.js.*$/, '');
})();

const money = n =>
  n == null ? null : 'NZ$' + Number(n).toLocaleString('en-NZ',
    { minimumFractionDigits: 2, maximumFractionDigits: 2 });

const esc = s => String(s ?? '').replace(/[&<>"]/g,
  c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

/* --- catalogue ---------------------------------------------------------- */

const Catalogue = {
  _d: null,
  async load() {
    if (this._d) return this._d;
    const r = await fetch(PREFIX + 'assets/data/catalogue.json');
    if (!r.ok) throw new Error('catalogue.json ' + r.status);
    return (this._d = await r.json());
  },
  /* `hidden` products are on the approved price list but must not be offered.
     They are filtered here so search, sort and the category grids all agree with
     the static markup the generator produced.
     NOTHING IS CURRENTLY HIDDEN. BD3216F was the only case, from 6 to 7 Aug
     2026; it was created in Zoho on 7 Aug, given a variant id and un-hidden.
     See apply-data-fixes.py, which owns the flag. The filter stays because the
     mechanism is what keeps JS and generated markup in step, not because there
     is anything to hide today. */
  all()        { return this._d.products.filter(p => !p.hidden); },
  cat(slug)    { return this._d.cats.find(c => c.slug === slug); },
  product(id)  { const p = this._d.products.find(x => x.id === id);
                 return p && !p.hidden ? p : undefined; },
  inCat(name)  { return this.all().filter(p => p.cat === name); },
  /* Set by mergeCatalogue in cms/products.js when the edge substituted at least
     one title or image. Absent on the built file, so this is false for every
     visitor until something is actually published. See hydrateTools. */
  hasOverrides() { return !!(this._d && this._d._cms); },
};

/* --- the shop's running order -------------------------------------------- */

/* `assets/data/shop-order.json` · two ordered lists of slugs, written by
   build-shop-pages.py and overridden at the edge by mergeShopOrder in
   cms/products.js when somebody has published an order through /admin.

       featured   the curated order. Ships as the whole range in price-list
                  order, which is the agreed default.
       order      the running order of everything, used for whatever is not
                  featured, and for the "Featured" sort inside a category.

   FETCHED ONLY WHERE IT IS USED, which is shop.html and the eight category
   pages. Product pages and the cart call Catalogue.load() and never touch this.
   It is also a SEPARATE FILE FROM THE CATALOGUE on purpose: an order override
   is permanent once set, and merging it into catalogue.json would permanently
   cost that 72KB file its 304 on every page of the site. See the note on
   SHOP_ORDER_PATH_RE in cms/products.js.

   A FAILURE HERE IS NOT FATAL. If the file is missing or unreadable the ranks
   are empty, every product sorts equal, and the tie-break by name means the
   grid falls back to A to Z. The static markup on the page is already correct,
   so a customer who never searches or sorts sees nothing at all. */
const Order = {
  featured: null,          // Map slug -> rank, or null when not loaded
  all: null,
  _cms: 0,
  async load() {
    if (this.featured) return;
    let d = null;
    try {
      const r = await fetch(PREFIX + 'assets/data/shop-order.json');
      if (r.ok) d = await r.json();
    } catch { /* fall through to the empty ranks below */ }
    const rank = (list) => new Map(
      Array.isArray(list) ? list.map((s, i) => [s, i]) : []);
    this.all = rank(d?.order);
    /* Absent `featured` means "everything is featured", not "nothing is". The
       built file always carries both, so this only matters if the file is
       hand-edited or an older one is cached. */
    this.featured = Array.isArray(d?.featured) ? rank(d.featured) : this.all;
    this._cms = Number(d?._cms) || 0;
  },
  /* Set by mergeShopOrder when the edge substituted a published order. Absent
     on the built file, so this is false for every visitor until an order is
     actually published, and hydrateTools does no work on load. */
  hasOverrides() { return this._cms > 0; },
};

/* ⚠ MIRRORS `in_running_order()` in build-shop-pages.py.
   That function lays out the SAME grid server-side; this one takes over the
   moment a customer types in the search box or changes the sort. HANDOFF 8a
   records what a disagreement between the two looks like: the grid visibly
   reorders mid-session for no reason the customer can see.

   Returns { head, tail }. `head` is the featured products in curated order,
   `tail` is everything else in full-range order. `tail` is empty in the shipped
   configuration, because everything is featured. It exists so that removing a
   product from Featured moves it down the page rather than deleting it from the
   shop, which is the one behaviour a curated default must never have. */
function arrange(list) {
  const F = Order.featured || new Map();
  const A = Order.all || new Map();
  const big = A.size + 1;
  const byName = (a, b) => a.name.localeCompare(b.name);
  const head = list.filter(p => F.has(p.slug))
    .sort((a, b) => F.get(a.slug) - F.get(b.slug));
  const tail = list.filter(p => !F.has(p.slug))
    .sort((a, b) => (A.has(a.slug) ? A.get(a.slug) : big)
                  - (A.has(b.slug) ? A.get(b.slug) : big) || byName(a, b));
  return { head, tail };
}

/* --- cart --------------------------------------------------------------- */

/* v2: cart lines are keyed by product + size, NOT by SKU.

   WHY: the price list carries two SKUs twice · FU3247 on both the Single and the
   Double of Makers Sofa Bed Replacement Mattress, and BD2236WN on both the Queen
   and the Super King of Weavers 220TC Premium Sheeting Flat Navy. Keying on SKU
   merged those two sizes into one line, so a customer who ordered a Double got
   quantity 2 of the Single at the Single's price. Remove and quantity controls
   hit the wrong line for the same reason.

   ✅ THE UNDERLYING DATA DEFECT IS FIXED AT SOURCE, and the warning that used to
   sit here about the order value being wrong by $90 and $20 is OBSOLETE. Do not
   go looking for it. apply-data-fixes.py reissued both SKUs, Super King is now
   BD2239WN and Double is FU3240, each with its own price and variant id.
   Verified 17 Aug 2026: all 367 variants in catalogue.json carry 367 DISTINCT
   SKUs, and the price list holds one row per SKU.

   Keying on product + size STAYS. It is what made the shop correct while the
   data was wrong, it costs nothing now the data is right, and it is the only
   key that stays unambiguous if a SKU is ever duplicated again.

   v1 carts are dropped rather than migrated: a v1 line cannot be resolved back
   to a size when its SKU is ambiguous, which is the whole bug. */
const KEY = 'tln.cart.v2';

/* ⚠ MIRRORS MAX_QTY in functions/api/cart.js, and it has to.
   The API refuses any line above this with a 422 BEFORE it reaches Zoho. With
   no matching ceiling here the shop happily built a cart the Checkout button
   could only reject: typing 99999 into a quantity box showed a subtotal of
   NZ$92,499,075.00 and a cart badge reading 99999, and the customer found out
   it was impossible only after pressing the money button. Clamp where the
   quantity is set, not where it is sent, so the number on screen is always a
   number that can actually be ordered. Raise both or neither. */
const MAX_QTY = 999;

const lineKey = (product, variant) => `${product.id}|${variant.size}`;

const Cart = {
  lines: [],
  load()  { try { this.lines = JSON.parse(localStorage.getItem(KEY)) || []; }
            catch { this.lines = []; }
            this.lines = this.lines.filter(l => l && l.key);
            /* CLAMP ON THE WAY IN, not only on the way out.
               Clamping every write is not enough on its own, because the cart
               outlives the code: `tln.cart.v2` sits in a real browser across
               deploys. Anyone who typed a huge quantity while the old unbounded
               version was live still has it, so the day this ships they would
               load the cart, see 5000 and a badge reading 5000, and only find
               out at the Checkout button that the API refuses anything over
               MAX_QTY. Verified by seeding qty 5000 straight into localStorage:
               before this line the page rendered it untouched and only
               self-corrected if the customer happened to press "+".
               A non-numeric or missing qty becomes 1 rather than removing the
               line, for the same reason the cart input refuses junk instead of
               deleting: losing a line silently is the worse failure. */
            let fixed = 0;
            this.lines.forEach(l => {
              const n = Math.floor(Number(l.qty));
              const q = Number.isFinite(n) ? Math.min(MAX_QTY, Math.max(1, n)) : 1;
              if (q !== l.qty) { l.qty = q; fixed += 1; }
            });
            /* Write the correction back, but ONLY when there was one, so an
               ordinary page view still does no work. Without this the display
               and the checkout payload were right while localStorage kept the
               old 5000 forever, which is the kind of split state that makes the
               next person debugging this doubt the clamp. */
            if (fixed) { this.save(); return; }
            this.paintCount(); },
  save()  { try { localStorage.setItem(KEY, JSON.stringify(this.lines)); } catch {}
            this.paintCount(); },
  add(product, variant, qty = 1) {
    if (variant.price == null) return;      // never cart an unpriced size
    const key = lineKey(product, variant);
    const line = this.lines.find(l => l.key === key);
    if (line) line.qty = Math.min(MAX_QTY, line.qty + qty);
    else this.lines.push({
      key, sku: variant.sku, vid: variant.vid || null, pid: product.id,
      slug: product.slug, name: product.name, size: variant.size,
      price: variant.price, qty: Math.min(MAX_QTY, qty),
    });
    this.save();
  },
  setQty(key, qty) {
    const l = this.lines.find(x => x.key === key);
    if (!l) return;
    l.qty = Math.min(MAX_QTY, Math.max(0, qty));
    if (!l.qty) this.lines = this.lines.filter(x => x.key !== key);
    this.save();
  },
  remove(key) { this.lines = this.lines.filter(l => l.key !== key); this.save(); },
  count()     { return this.lines.reduce((n, l) => n + l.qty, 0); },
  subtotal()  { return this.lines.reduce((n, l) => n + l.qty * (l.price || 0), 0); },
  paintCount(){ document.querySelectorAll('[data-cart-count]')
                  .forEach(e => e.textContent = this.count()); },
};

/* Freight · mirrors policies.html and the live Zoho zones. Zoho's bands are
   inclusive at the lower end: 0.01–29.99 / 30–149.99 / 150–349.99 / 350+.
   An order of exactly $350.00 ships free; quoting 28.90 there would show more
   than Zoho charges at checkout. Rural adds a flat $9.00 at every tier.
   Once SOURCE.mode is 'zoho' the Checkout API returns the real rates and this
   becomes a pre-checkout estimate only.

   Rates raised 4 Sep 2026: the two middle tiers went 17.90 -> 18.90 and
   27.90 -> 28.90, with rural following at 27.90 and 37.90 so the flat +$9.00
   the policy page publishes stays true. Under $30 and free-over-$350 are
   unchanged. The reasoning and the audit trail are in policies.html and in
   test-freight-bands.mjs, neither of which is served to customers. */
function freight(subtotal, rural = false) {
  if (subtotal <= 0) return 0;
  const base = subtotal >= 350 ? 0
             : subtotal >= 150 ? 28.90
             : subtotal >= 30  ? 18.90
             : 9.90;
  return base + (rural ? 9.00 : 0);
}

/* --- product pages ------------------------------------------------------ */

function hydrateProduct(root) {
  const p = Catalogue.product(root.dataset.product);
  if (!p) return;

  /* Priced-ness is derived per variant, never from p.unpriced · that field is a
     COUNT of unpriced variants and reading it as a boolean rendered six products
     with priced sizes as "Price on application" with Add disabled. */
  const allPoa = p.variants.every(v => v.price == null);
  let i = p.variants.findIndex(v => v.price != null);
  if (i < 0) i = 0;
  let qty = 1;

  const price = root.querySelector('[data-price]');
  const sku   = root.querySelector('[data-sku]');
  const qtyIn = root.querySelector('[data-qty-val]');
  const add   = root.querySelector('[data-add]');
  const sizes = [...root.querySelectorAll('.shop-size')];

  /* --- the gallery, added 2 Sep 2026 ---------------------------------------
     THE HERO IS NOT INSIDE `root`. `root` is the [data-product] body column;
     the photograph is its SIBLING inside .shop-product__grid. Querying root
     for it silently finds nothing, which is a five-minute bug to write and a
     long one to spot.

     Everything here degrades to nothing. The server already rendered the
     correct opening hero, so a missing or malformed payload costs the swap
     and no more. */
  const grid = root.closest('.shop-product__grid') || document;
  const heroImg = grid.querySelector('[data-hero]');
  const thumbs = [...grid.querySelectorAll('.prod-thumb')];

  let photos = [];
  try {
    const tag = grid.querySelector('[data-cms-photos]');
    if (tag) {
      const parsed = JSON.parse(tag.textContent);
      if (Array.isArray(parsed)) photos = parsed;
    }
  } catch (err) {
    console.error('[TLN] gallery payload unreadable', err);
    photos = [];
  }

  /* A variant's own photograph, else the first general shot, else the first
     row. Mirrors photoForSku in cms/products.js; the two must agree, because
     the server picks the opening hero and this picks every one after it. */
  const photoFor = (wantSku) => {
    if (!photos.length) return null;
    const want = String(wantSku || '').trim().toUpperCase();
    return (want && photos.find((x) => x.sku
                && String(x.sku).toUpperCase() === want))
      || photos.find((x) => !x.sku)
      || photos[0];
  };

  const setHero = (ph) => {
    if (!heroImg || !ph || !ph.src) return;
    if (heroImg.getAttribute('src') !== ph.src) {
      heroImg.setAttribute('src', ph.src);
      heroImg.setAttribute('alt', ph.alt || p.name || '');
      /* Keep the intrinsic size honest. The server sent the opening hero's
         dimensions; a swapped photograph may differ, and a stale pair makes
         the browser scale to the wrong box. */
      if (ph.width && ph.height) {
        heroImg.setAttribute('width', String(ph.width));
        heroImg.setAttribute('height', String(ph.height));
      }
    }
    thumbs.forEach((b) => {
      const row = photos[+b.dataset.n];
      if (row && row.src === ph.src) b.setAttribute('aria-current', 'true');
      else b.removeAttribute('aria-current');
    });
  };

  thumbs.forEach((b) => b.addEventListener('click',
    () => setHero(photos[+b.dataset.n])));

  const paint = () => {
    const v = p.variants[i];
    const poa = v.price == null;
    if (!allPoa) {
      price.innerHTML = poa
        ? '<span class="shop-poa">Price on application</span>'
        : esc(money(v.price));
    }
    sku.textContent = 'SKU ' + v.sku;
    /* One more thing paint() owns, alongside price, SKU, the radiogroup and
       the Add button: the photograph for the size now chosen. */
    setHero(photoFor(v.sku));
    sizes.forEach((b, n) => b.setAttribute('aria-checked', String(n === i)));
    if (add && !allPoa) {
      add.disabled = poa;
      add.textContent = poa ? 'Enquire' : 'Add to Nest';
    }
    qtyIn.value = qty;
  };

  sizes.forEach(b => b.addEventListener('click', () => { i = +b.dataset.i; paint(); }));
  /* Both bounds matter. The lower one always existed; the upper one mirrors
     MAX_QTY, so this box cannot build a quantity /api/cart will refuse. */
  root.querySelectorAll('[data-qty]').forEach(b =>
    b.addEventListener('click', () => {
      qty = Math.min(MAX_QTY, Math.max(1, qty + (b.dataset.qty === '+' ? 1 : -1)));
      paint();
    }));
  qtyIn.addEventListener('change', () => {
    qty = Math.min(MAX_QTY, Math.max(1, parseInt(qtyIn.value, 10) || 1)); paint();
  });

  if (add && !allPoa) add.addEventListener('click', () => {
    if (p.variants[i].price == null) return;
    Cart.add(p, p.variants[i], qty);
    add.textContent = 'Added ✓';
    setTimeout(paint, 1400);
    document.dispatchEvent(new CustomEvent('tln:add_to_cart', { detail: {
      sku: p.variants[i].sku, name: p.name, category: p.cat,
      size: p.variants[i].size, price: p.variants[i].price, qty,
    }}));
  });

  paint();
  /* Fires once, on load, for whichever size is selected by default -- not
     re-fired on a size switch. GA4's own view_item is a page-level signal;
     re-firing it per click would double-count a product view as several. */
  document.dispatchEvent(new CustomEvent('tln:view_item', { detail: {
    sku: p.variants[i].sku, name: p.name, category: p.cat,
    price: p.variants[i].price,
  }}));
}

/* --- product imagery ----------------------------------------------------- */
/* ⚠ MIRRORS img_markup() / img_url() in build-shop-pages.py. Both render the
   SAME tile -- the generator server-side, this one on hydration when a customer
   searches or sorts. HANDOFF 8a records the trap: change one and not the other
   and the grid changes appearance mid-session.

   The DATA cannot drift, because `p.img` is written into catalogue.json by the
   generator and read here. Only the MARKUP has to be kept in step by hand.

   `p.img` is the compact record, expanded to filenames as `<stem>-<w>.<ext>`
   (or `<stem>.<ext>` when the width is 0):
       {f: stem, a: alt, w: 922, h: 1152, r: {avif: [400,800], jpg: [400,800,922]}}
   Absent `img` means not photographed yet -> keep the striped placeholder.

   THE SECOND SHAPE, added 17 Aug 2026:
       {u: '/media/<r2_key>', a: alt, w: 1254, h: 1254}
   A photograph uploaded through the CMS is ONE content-addressed R2 object with
   no renditions on disk, so there is nothing to expand into a srcset. `u` is a
   site-absolute URL and the `prefix` must NOT be applied to it: the same record
   is read from shop.html at the root and from a category page one level down.

   Before this, `mergeCatalogue` merged titles only, so a CMS upload appeared on
   the product page and the tile still read "Photography to come". It renders a
   plain <img>: the browser fetches the original at whatever size the tile is,
   which is why the upload endpoint caps at 8 MB and why the BULK photography
   path (product-images.json, real renditions on disk) stays the one to use for
   all 173 products. This shape is the exception, not the rollout. */

const FB_ORDER = ['jpg', 'jpeg', 'webp', 'avif'];   // most decodable first

/* Same numbers as SIZES_TILE in build-shop-pages.py, derived from shop.css:
   .shop-grid is 4 cols (gap 28px) inside .container (max 1440, --pad 56),
   3 cols <=1100px, 2 cols <=860px. Widest a tile renders is 311px. */
const SIZES_TILE = '(max-width: 860px) 46vw, (max-width: 1100px) 30vw, 311px';
/* .shop-line thumbnail column is 88px, 64px at <=560px. */
const SIZES_THUMB = '(max-width: 560px) 64px, 88px';

const imgUrl = (img, ext, w, prefix) =>
  `${prefix}assets/img/products/${w ? `${img.f}-${w}` : img.f}.${ext}`;

function imgMarkup(img, prefix, sizes, eager) {
  if (!img) return null;
  /* Single-URL record: no renditions exist, so no <picture> and no sizes. */
  if (img.u) {
    const load = eager ? 'fetchpriority="high"' : 'loading="lazy"';
    return `<img src="${esc(img.u)}" alt="${esc(img.a || '')}"`
      + (img.w && img.h ? ` width="${img.w}" height="${img.h}"` : '')
      + ` ${load} decoding="async">`;
  }
  if (!img.r) return null;
  const srcs = [];
  for (const [ext, mime] of [['avif', 'image/avif'], ['webp', 'image/webp']]) {
    const ws = (img.r[ext] || []).filter(w => w);
    if (ws.length) {
      const ss = ws.map(w => `${imgUrl(img, ext, w, prefix)} ${w}w`).join(', ');
      srcs.push(`<source type="${mime}" srcset="${ss}" sizes="${sizes}">`);
    }
  }
  const fbExt = FB_ORDER.find(x => img.r[x]);
  if (!fbExt) return null;
  const fbWs = img.r[fbExt];
  const fbSs = fbWs.filter(w => w)
    .map(w => `${imgUrl(img, fbExt, w, prefix)} ${w}w`).join(', ');
  const load = eager ? 'fetchpriority="high"' : 'loading="lazy"';
  const tag = `<img src="${imgUrl(img, fbExt, Math.max(...fbWs), prefix)}"`
    + (fbSs ? ` srcset="${fbSs}" sizes="${sizes}"` : '')
    + ` alt="${esc(img.a)}" width="${img.w}" height="${img.h}"`
    + ` ${load} decoding="async">`;
  return srcs.length ? `<picture>${srcs.join('')}${tag}</picture>` : tag;
}

/* The `.ph` block for a product, filled or striped. `extra` carries the
   context class (shop-tile__ph / shop-line__ph) so callers stay one-liners. */
function phBlock(p, prefix, sizes, extra, cap) {
  const inner = imgMarkup(p && p.img, prefix, sizes, false);
  /* r-1-1: PRODUCT ratio, agreed 17 Aug 2026. MIRRORS ph_block() in
     build-shop-pages.py. If these two disagree a tile changes shape the moment
     the customer types in the search box, because that is when this renderer
     takes over from the built markup. */
  const cls = `ph r-1-1${extra ? ' ' + extra : ''}${inner ? ' has-img' : ''}`;
  return `<span class="${cls}">${inner || (cap ? '<span class="ph__cap">Photography to come</span>' : '')}</span>`;
}

