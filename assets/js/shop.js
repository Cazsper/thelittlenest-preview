/* ============================================================================
   THE LITTLE NEST — SHOP

   The shop is now STATIC PAGES, not a single-page app. Every product and
   category is a real HTML file generated by build-shop-pages.py, so the
   content is in the markup and search engines can index it. This file only
   *hydrates* those pages: size switching, quantity, add-to-cart, search/sort,
   and the cart itself.

   Do not move rendering back into JS. The whole point of the static pages is
   that the content exists without them.

   GOING LIVE
   Catalogue and cart read through adapters so the UI never knows the source.
   Set SOURCE.mode = 'zoho' and the same screens run on the live Zoho cart,
   freight and checkout.

   Verified 6 Aug 2026: the Storefront API answers on the .com.au data centre
   with header `domain-name: staging.thelittlenest.co.nz`. /cart returns live
   JSON. Catalogue endpoints return 200-empty until the store is published,
   which is the one remaining dependency.
   ========================================================================= */

const SOURCE = {
  mode: 'local',                                        // 'local' | 'zoho'
  base: 'https://commerce.zoho.com.au/storefront/api/v1',
  domain: 'staging.thelittlenest.co.nz',
};

/* Pages live at the root and in /products/ and /categories/, so asset paths
   are relative. Work out the prefix once from where this script was loaded. */
const PREFIX = (() => {
  const s = document.currentScript || [...document.scripts].pop();
  return (s?.src || '').replace(/assets\/js\/shop\.js.*$/, '');
})();

const money = n =>
  n == null ? null : 'NZ$' + Number(n).toLocaleString('en-NZ',
    { minimumFractionDigits: 2, maximumFractionDigits: 2 });

const esc = s => String(s ?? '').replace(/[&<>"]/g,
  c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

/* --- catalogue ---------------------------------------------------------- */

const Catalogue = {
  _d: null,
  async load() {
    if (this._d) return this._d;
    const r = await fetch(PREFIX + 'assets/data/catalogue.json');
    if (!r.ok) throw new Error('catalogue.json ' + r.status);
    return (this._d = await r.json());
  },
  all()        { return this._d.products; },
  cat(slug)    { return this._d.cats.find(c => c.slug === slug); },
  product(id)  { return this._d.products.find(p => p.id === id); },
  inCat(name)  { return this._d.products.filter(p => p.cat === name); },
};

/* --- cart --------------------------------------------------------------- */

const KEY = 'tln.cart.v1';

const Cart = {
  lines: [],
  load()  { try { this.lines = JSON.parse(localStorage.getItem(KEY)) || []; }
            catch { this.lines = []; } this.paintCount(); },
  save()  { try { localStorage.setItem(KEY, JSON.stringify(this.lines)); } catch {}
            this.paintCount(); },
  add(product, variant, qty = 1) {
    const line = this.lines.find(l => l.sku === variant.sku);
    if (line) line.qty += qty;
    else this.lines.push({
      sku: variant.sku, vid: variant.vid || null, pid: product.id,
      slug: product.slug, name: product.name, size: variant.size,
      price: variant.price, qty,
    });
    this.save();
  },
  setQty(sku, qty) {
    const l = this.lines.find(x => x.sku === sku);
    if (!l) return;
    l.qty = Math.max(0, qty);
    if (!l.qty) this.lines = this.lines.filter(x => x.sku !== sku);
    this.save();
  },
  remove(sku) { this.lines = this.lines.filter(l => l.sku !== sku); this.save(); },
  count()     { return this.lines.reduce((n, l) => n + l.qty, 0); },
  subtotal()  { return this.lines.reduce((n, l) => n + l.qty * (l.price || 0), 0); },
  paintCount(){ document.querySelectorAll('[data-cart-count]')
                  .forEach(e => e.textContent = this.count()); },
};

/* Freight — mirrors policies.html and the live Zoho zones. Zoho's bands are
   inclusive at the lower end: 0.01–29.99 / 30–149.99 / 150–349.99 / 350+.
   An order of exactly $350.00 ships free; quoting 27.90 there would show more
   than Zoho charges at checkout. Rural adds a flat $9.00 at every tier.
   Once SOURCE.mode is 'zoho' the Checkout API returns the real rates and this
   becomes a pre-checkout estimate only. */
function freight(subtotal, rural = false) {
  if (subtotal <= 0) return 0;
  const base = subtotal >= 350 ? 0
             : subtotal >= 150 ? 27.90
             : subtotal >= 30  ? 17.90
             : 9.90;
  return base + (rural ? 9.00 : 0);
}

/* --- product pages ------------------------------------------------------ */

function hydrateProduct(root) {
  const p = Catalogue.product(root.dataset.product);
  if (!p) return;
  let i = 0, qty = 1;

  const price = root.querySelector('[data-price]');
  const sku   = root.querySelector('[data-sku]');
  const qtyIn = root.querySelector('[data-qty-val]');
  const sizes = [...root.querySelectorAll('.shop-size')];

  const paint = () => {
    const v = p.variants[i];
    if (!p.unpriced) price.textContent = money(v.price);
    sku.textContent = 'SKU ' + v.sku;
    sizes.forEach((b, n) => b.setAttribute('aria-checked', String(n === i)));
    qtyIn.value = qty;
  };

  sizes.forEach(b => b.addEventListener('click', () => { i = +b.dataset.i; paint(); }));
  root.querySelectorAll('[data-qty]').forEach(b =>
    b.addEventListener('click', () => {
      qty = Math.max(1, qty + (b.dataset.qty === '+' ? 1 : -1)); paint();
    }));
  qtyIn.addEventListener('change', () => {
    qty = Math.max(1, parseInt(qtyIn.value, 10) || 1); paint();
  });

  const add = root.querySelector('[data-add]');
  if (add && !p.unpriced) add.addEventListener('click', () => {
    Cart.add(p, p.variants[i], qty);
    add.textContent = 'Added ✓';
    setTimeout(() => { add.textContent = 'Add to Nest'; }, 1400);
  });

  paint();
}

/* --- search + sort on shop.html and category pages ---------------------- */

function tile(p, prefix) {
  const price = p.unpriced ? '<span class="shop-poa">Price on application</span>'
    : (p.lo === p.hi ? money(p.lo) : `${money(p.lo)} – ${money(p.hi)}`);
  return `<a class="shop-tile" href="${prefix}products/${esc(p.slug)}.html">
    <span class="ph r-4-5 shop-tile__ph"><span class="ph__cap">Photography to come</span></span>
    <span class="shop-tile__name">${esc(p.name)}</span>
    <span class="shop-tile__price">${price}</span>
  </a>`;
}

function hydrateTools(tools) {
  const scope = tools.dataset.scope;
  const grid  = document.querySelector('[data-grid]');
  const count = tools.querySelector('[data-count]');
  const q     = tools.querySelector('[data-q]');
  const sort  = tools.querySelector('[data-sort]');
  if (!grid) return;

  // category pages sit one level down; shop.html is at the root
  const prefix = scope === 'all' ? '' : '../';

  const paint = () => {
    const term = (q?.value || '').trim().toLowerCase();
    let list = scope === 'all'
      ? Catalogue.all().slice()
      : Catalogue.inCat(Catalogue.cat(scope).name).slice();

    if (term) list = list.filter(p =>
      p.name.toLowerCase().includes(term) ||
      p.variants.some(v => (v.sku || '').toLowerCase().includes(term)));

    const s = sort?.value || 'az';
    if (s === 'lo')      list.sort((a, b) => (a.lo == null) - (b.lo == null) || a.lo - b.lo);
    else if (s === 'hi') list.sort((a, b) => (a.hi == null) - (b.hi == null) || b.hi - a.hi);
    else                 list.sort((a, b) => a.name.localeCompare(b.name));

    grid.innerHTML = list.length
      ? list.map(p => tile(p, prefix)).join('')
      : '<p class="shop-empty">Nothing matches that search.</p>';
    if (count) count.textContent =
      list.length + (list.length === 1 ? ' product' : ' products');
  };

  q?.addEventListener('input', paint);
  sort?.addEventListener('change', paint);
}

/* --- cart page ---------------------------------------------------------- */

function renderCart() {
  const root = document.getElementById('cart-root');
  if (!root) return;

  if (!Cart.lines.length) {
    root.innerHTML = `
      <section class="container shop-head">
        <h1 class="serif">Your Nest is empty</h1>
        <p class="shop-head__lede">Nothing here yet.</p>
        <p><a class="btn" href="shop.html">Shop the range →</a></p>
      </section>`;
    return;
  }

  const sub = Cart.subtotal();
  const fr = freight(sub);
  root.innerHTML = `
  <section class="container shop-head"><h1 class="serif">Your Nest</h1></section>
  <section class="container shop-cart">
    <div class="shop-cart__lines">
      ${Cart.lines.map(l => `
        <div class="shop-line">
          <span class="ph r-4-5 shop-line__ph"></span>
          <div class="shop-line__body">
            <a class="shop-line__name" href="products/${esc(l.slug)}.html">${esc(l.name)}</a>
            <p class="shop-line__meta">${esc(l.size)} · SKU ${esc(l.sku)}</p>
            <button class="shop-line__rm" type="button" data-rm="${esc(l.sku)}">Remove</button>
          </div>
          <div class="shop-qty shop-qty--sm">
            <button type="button" data-line="-" data-sku="${esc(l.sku)}" aria-label="Decrease">–</button>
            <input type="text" inputmode="numeric" value="${l.qty}" data-line-val="${esc(l.sku)}" aria-label="Quantity">
            <button type="button" data-line="+" data-sku="${esc(l.sku)}" aria-label="Increase">+</button>
          </div>
          <span class="shop-line__price">${money(l.qty * l.price)}</span>
        </div>`).join('')}
    </div>
    <aside class="shop-sum">
      <h2 class="caps">Summary</h2>
      <p class="shop-sum__row"><span>Subtotal</span><span>${money(sub)}</span></p>
      <p class="shop-sum__row"><span>Freight</span><span>${fr === 0 ? 'Free' : money(fr)}</span></p>
      <p class="shop-sum__note">Rural delivery adds $9.00. Final freight is
        confirmed at checkout against your address.</p>
      <p class="shop-sum__total"><span>Total</span><span>${money(sub + fr)}</span></p>
      <button class="btn shop-checkout" type="button" data-checkout>Checkout →</button>
      <p class="shop-sum__note">GST inclusive. Payment is taken securely by Stripe.</p>
    </aside>
  </section>`;

  root.querySelectorAll('[data-rm]').forEach(b =>
    b.addEventListener('click', () => { Cart.remove(b.dataset.rm); renderCart(); }));
  root.querySelectorAll('[data-line]').forEach(b =>
    b.addEventListener('click', () => {
      const l = Cart.lines.find(x => x.sku === b.dataset.sku);
      Cart.setQty(b.dataset.sku, l.qty + (b.dataset.line === '+' ? 1 : -1));
      renderCart();
    }));
  root.querySelectorAll('[data-line-val]').forEach(inp =>
    inp.addEventListener('change', () => {
      Cart.setQty(inp.dataset.lineVal, parseInt(inp.value, 10) || 0);
      renderCart();
    }));
  root.querySelector('[data-checkout]')?.addEventListener('click', checkout);
}

/* Checkout hands the cart to Zoho, which owns payment, tax, freight and the
   sales order. Until the store is published there is nothing to hand it to,
   so say so plainly rather than failing silently. */
async function checkout() {
  if (SOURCE.mode !== 'zoho') {
    alert('Checkout is not connected yet.\n\n' +
      'The shop, cart and freight all work. Payment needs the Zoho store ' +
      'published so its Storefront API can take the order — that is the one ' +
      'remaining step.');
    return;
  }
  for (const l of Cart.lines) {
    await fetch(`${SOURCE.base}/cart`, {
      method: 'POST',
      headers: { 'domain-name': SOURCE.domain, 'Content-Type': 'application/json' },
      credentials: 'include',
      body: JSON.stringify({ product_variant_id: l.vid, quantity: String(l.qty) }),
    });
  }
  location.href = `https://${SOURCE.domain}/checkout`;
}

/* --- boot --------------------------------------------------------------- */

(async function init() {
  Cart.load();

  const product = document.querySelector('[data-product]');
  const tools   = document.querySelector('.shop-tools');
  const cart    = document.getElementById('cart-root');
  if (!product && !tools && !cart) return;   // an ordinary page, nothing to do

  try {
    await Catalogue.load();
  } catch (err) {
    console.error('[TLN] catalogue failed to load', err);
    return;   // static content stays on screen; only interactivity is lost
  }

  if (product) hydrateProduct(product);
  if (tools)   hydrateTools(tools);
  if (cart)    renderCart();
})();
