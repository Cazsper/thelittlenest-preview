/* ============================================================================
   THE LITTLE NEST — SHOP

   The shop is now STATIC PAGES, not a single-page app. Every product and
   category is a real HTML file generated by build-shop-pages.py, so the
   content is in the markup and search engines can index it. This file only
   *hydrates* those pages: size switching, quantity, add-to-cart, search/sort,
   and the cart itself.

   Do not move rendering back into JS. The whole point of the static pages is
   that the content exists without them.

   GOING LIVE
   Set SOURCE.mode = 'zoho' and the Checkout button starts handing real carts to
   Zoho. That is the ONLY switch; everything behind it is built and tested.

   ⚠ DO NOT FLIP IT UNTIL A REAL TEST ORDER HAS BEEN PLACED AND CONFIRMED.
   Cart seeding, validation, error handling and the session handoff are all
   proven (10 Aug). What is NOT yet proven end to end is what happens after the
   customer reaches Zoho's checkout: GST, freight, payment, the sales order, and
   whether the courier pipeline fires on a REAL web order rather than a manually
   created one. Flipping this early points live customers at an untested path.

   ⚠ IT ALSO REQUIRES A SHARED PARENT DOMAIN.
   The handoff works by a `zcid` cookie that the browser must send to Zoho's
   storefront host. That is only possible when this site and the storefront share
   a registrable domain — `thelittlenest.co.nz` and `staging.thelittlenest.co.nz`
   do. It CANNOT work from *.pages.dev, which is a public suffix. See
   functions/api/cart.js.
   ========================================================================= */

const SOURCE = {
  mode: 'local',            // 'local' | 'zoho' — see the warning above
};

/* Pages live at the root and in /products/ and /categories/, so asset paths
   are relative. Work out the prefix once from where this script was loaded. */
const PREFIX = (() => {
  const s = document.currentScript || [...document.scripts].pop();
  return (s?.src || '').replace(/assets\/js\/shop\.js.*$/, '');
})();

const money = n =>
  n == null ? null : 'NZ$' + Number(n).toLocaleString('en-NZ',
    { minimumFractionDigits: 2, maximumFractionDigits: 2 });

const esc = s => String(s ?? '').replace(/[&<>"]/g,
  c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

/* --- catalogue ---------------------------------------------------------- */

const Catalogue = {
  _d: null,
  async load() {
    if (this._d) return this._d;
    const r = await fetch(PREFIX + 'assets/data/catalogue.json');
    if (!r.ok) throw new Error('catalogue.json ' + r.status);
    return (this._d = await r.json());
  },
  /* `hidden` products are on the approved price list but must not be offered —
     currently only BD3216F, which Zoho has no record of and so cannot fulfil.
     They are filtered here so search, sort and the category grids all agree with
     the static markup the generator produced. */
  all()        { return this._d.products.filter(p => !p.hidden); },
  cat(slug)    { return this._d.cats.find(c => c.slug === slug); },
  product(id)  { const p = this._d.products.find(x => x.id === id);
                 return p && !p.hidden ? p : undefined; },
  inCat(name)  { return this.all().filter(p => p.cat === name); },
};

/* --- cart --------------------------------------------------------------- */

/* v2: cart lines are keyed by product + size, NOT by SKU.

   WHY: the price list carries two SKUs twice — FU3247 on both the Single and the
   Double of Makers Sofa Bed Replacement Mattress, and BD2236WN on both the Queen
   and the Super King of Weavers 220TC Premium Sheeting Flat Navy. Keying on SKU
   merged those two sizes into one line, so a customer who ordered a Double got
   quantity 2 of the Single at the Single's price. Remove and quantity controls
   hit the wrong line for the same reason.

   The underlying data defect still needs fixing at source — Zoho holds only one
   product per duplicated SKU, at the lower price, so the ORDER value is wrong by
   $90 and $20 until new SKUs are issued. This only stops the shop compounding it.

   v1 carts are dropped rather than migrated: a v1 line cannot be resolved back
   to a size when its SKU is ambiguous, which is the whole bug. */
const KEY = 'tln.cart.v2';

const lineKey = (product, variant) => `${product.id}|${variant.size}`;

const Cart = {
  lines: [],
  load()  { try { this.lines = JSON.parse(localStorage.getItem(KEY)) || []; }
            catch { this.lines = []; }
            this.lines = this.lines.filter(l => l && l.key);
            this.paintCount(); },
  save()  { try { localStorage.setItem(KEY, JSON.stringify(this.lines)); } catch {}
            this.paintCount(); },
  add(product, variant, qty = 1) {
    if (variant.price == null) return;      // never cart an unpriced size
    const key = lineKey(product, variant);
    const line = this.lines.find(l => l.key === key);
    if (line) line.qty += qty;
    else this.lines.push({
      key, sku: variant.sku, vid: variant.vid || null, pid: product.id,
      slug: product.slug, name: product.name, size: variant.size,
      price: variant.price, qty,
    });
    this.save();
  },
  setQty(key, qty) {
    const l = this.lines.find(x => x.key === key);
    if (!l) return;
    l.qty = Math.max(0, qty);
    if (!l.qty) this.lines = this.lines.filter(x => x.key !== key);
    this.save();
  },
  remove(key) { this.lines = this.lines.filter(l => l.key !== key); this.save(); },
  count()     { return this.lines.reduce((n, l) => n + l.qty, 0); },
  subtotal()  { return this.lines.reduce((n, l) => n + l.qty * (l.price || 0), 0); },
  paintCount(){ document.querySelectorAll('[data-cart-count]')
                  .forEach(e => e.textContent = this.count()); },
};

/* Freight — mirrors policies.html and the live Zoho zones. Zoho's bands are
   inclusive at the lower end: 0.01–29.99 / 30–149.99 / 150–349.99 / 350+.
   An order of exactly $350.00 ships free; quoting 27.90 there would show more
   than Zoho charges at checkout. Rural adds a flat $9.00 at every tier.
   Once SOURCE.mode is 'zoho' the Checkout API returns the real rates and this
   becomes a pre-checkout estimate only. */
function freight(subtotal, rural = false) {
  if (subtotal <= 0) return 0;
  const base = subtotal >= 350 ? 0
             : subtotal >= 150 ? 27.90
             : subtotal >= 30  ? 17.90
             : 9.90;
  return base + (rural ? 9.00 : 0);
}

/* --- product pages ------------------------------------------------------ */

function hydrateProduct(root) {
  const p = Catalogue.product(root.dataset.product);
  if (!p) return;

  /* Priced-ness is derived per variant, never from p.unpriced — that field is a
     COUNT of unpriced variants and reading it as a boolean rendered six products
     with priced sizes as "Price on application" with Add disabled. */
  const allPoa = p.variants.every(v => v.price == null);
  let i = p.variants.findIndex(v => v.price != null);
  if (i < 0) i = 0;
  let qty = 1;

  const price = root.querySelector('[data-price]');
  const sku   = root.querySelector('[data-sku]');
  const qtyIn = root.querySelector('[data-qty-val]');
  const add   = root.querySelector('[data-add]');
  const sizes = [...root.querySelectorAll('.shop-size')];

  const paint = () => {
    const v = p.variants[i];
    const poa = v.price == null;
    if (!allPoa) {
      price.innerHTML = poa
        ? '<span class="shop-poa">Price on application</span>'
        : esc(money(v.price));
    }
    sku.textContent = 'SKU ' + v.sku;
    sizes.forEach((b, n) => b.setAttribute('aria-checked', String(n === i)));
    if (add && !allPoa) {
      add.disabled = poa;
      add.textContent = poa ? 'Enquire' : 'Add to Nest';
    }
    qtyIn.value = qty;
  };

  sizes.forEach(b => b.addEventListener('click', () => { i = +b.dataset.i; paint(); }));
  root.querySelectorAll('[data-qty]').forEach(b =>
    b.addEventListener('click', () => {
      qty = Math.max(1, qty + (b.dataset.qty === '+' ? 1 : -1)); paint();
    }));
  qtyIn.addEventListener('change', () => {
    qty = Math.max(1, parseInt(qtyIn.value, 10) || 1); paint();
  });

  if (add && !allPoa) add.addEventListener('click', () => {
    if (p.variants[i].price == null) return;
    Cart.add(p, p.variants[i], qty);
    add.textContent = 'Added ✓';
    setTimeout(paint, 1400);
  });

  paint();
}

/* --- search + sort on shop.html and category pages ---------------------- */

function tile(p, prefix) {
  /* Same derivation as the generator: a product is POA only when EVERY size is,
     and the range is taken from the priced sizes. Must stay in step with
     price_label() in build-shop-pages.py or the hydrated grid will disagree with
     the static markup it replaces. */
  const ps = p.variants.filter(v => v.price != null).map(v => v.price);
  const price = !ps.length
    ? '<span class="shop-poa">Price on application</span>'
    : (Math.min(...ps) === Math.max(...ps)
        ? money(Math.min(...ps))
        : `${money(Math.min(...ps))} – ${money(Math.max(...ps))}`);
  return `<a class="shop-tile" href="${prefix}products/${esc(p.slug)}.html">
    <span class="ph r-4-5 shop-tile__ph"><span class="ph__cap">Photography to come</span></span>
    <span class="shop-tile__name">${esc(p.name)}</span>
    <span class="shop-tile__price">${price}</span>
  </a>`;
}

function hydrateTools(tools) {
  const scope = tools.dataset.scope;
  const grid  = document.querySelector('[data-grid]');
  const count = tools.querySelector('[data-count]');
  const q     = tools.querySelector('[data-q]');
  const sort  = tools.querySelector('[data-sort]');
  if (!grid) return;

  // category pages sit one level down; shop.html is at the root
  const prefix = scope === 'all' ? '' : '../';

  const paint = () => {
    const term = (q?.value || '').trim().toLowerCase();
    let list = scope === 'all'
      ? Catalogue.all().slice()
      : Catalogue.inCat(Catalogue.cat(scope).name).slice();

    if (term) list = list.filter(p =>
      p.name.toLowerCase().includes(term) ||
      p.variants.some(v => (v.sku || '').toLowerCase().includes(term)));

    const s = sort?.value || 'az';
    if (s === 'lo')      list.sort((a, b) => (a.lo == null) - (b.lo == null) || a.lo - b.lo);
    else if (s === 'hi') list.sort((a, b) => (a.hi == null) - (b.hi == null) || b.hi - a.hi);
    else                 list.sort((a, b) => a.name.localeCompare(b.name));

    grid.innerHTML = list.length
      ? list.map(p => tile(p, prefix)).join('')
      : '<p class="shop-empty">Nothing matches that search.</p>';
    if (count) count.textContent =
      list.length + (list.length === 1 ? ' product' : ' products');
  };

  q?.addEventListener('input', paint);
  sort?.addEventListener('change', paint);
}

/* --- cart page ---------------------------------------------------------- */

function renderCart() {
  const root = document.getElementById('cart-root');
  if (!root) return;

  if (!Cart.lines.length) {
    root.innerHTML = `
      <section class="container shop-head">
        <h1 class="serif">Your Nest is empty</h1>
        <p class="shop-head__lede">Nothing here yet.</p>
        <p><a class="btn" href="shop.html">Shop the range →</a></p>
      </section>`;
    return;
  }

  const sub = Cart.subtotal();
  const fr = freight(sub);
  root.innerHTML = `
  <section class="container shop-head"><h1 class="serif">Your Nest</h1></section>
  <section class="container shop-cart">
    <div class="shop-cart__lines">
      ${Cart.lines.map(l => `
        <div class="shop-line">
          <span class="ph r-4-5 shop-line__ph"></span>
          <div class="shop-line__body">
            <a class="shop-line__name" href="products/${esc(l.slug)}.html">${esc(l.name)}</a>
            <p class="shop-line__meta">${esc(l.size)} · SKU ${esc(l.sku)}</p>
            <button class="shop-line__rm" type="button" data-rm="${esc(l.key)}">Remove</button>
          </div>
          <div class="shop-qty shop-qty--sm">
            <button type="button" data-line="-" data-key="${esc(l.key)}" aria-label="Decrease">–</button>
            <input type="text" inputmode="numeric" value="${l.qty}" data-line-val="${esc(l.key)}" aria-label="Quantity">
            <button type="button" data-line="+" data-key="${esc(l.key)}" aria-label="Increase">+</button>
          </div>
          <span class="shop-line__price">${money(l.qty * l.price)}</span>
        </div>`).join('')}
    </div>
    <aside class="shop-sum">
      <h2 class="caps">Summary</h2>
      <p class="shop-sum__row"><span>Subtotal</span><span>${money(sub)}</span></p>
      <p class="shop-sum__row"><span>Freight</span><span>${fr === 0 ? 'Free' : money(fr)}</span></p>
      <p class="shop-sum__note">Rural delivery adds $9.00. Final freight is
        confirmed at checkout against your address.</p>
      <p class="shop-sum__total"><span>Total</span><span>${money(sub + fr)}</span></p>
      <button class="btn shop-checkout" type="button" data-checkout>Checkout →</button>
      <p class="shop-sum__note">GST inclusive. Payment is taken securely by Stripe.</p>
    </aside>
  </section>`;

  root.querySelectorAll('[data-rm]').forEach(b =>
    b.addEventListener('click', () => { Cart.remove(b.dataset.rm); renderCart(); }));
  root.querySelectorAll('[data-line]').forEach(b =>
    b.addEventListener('click', () => {
      const l = Cart.lines.find(x => x.key === b.dataset.key);
      if (!l) return;
      Cart.setQty(l.key, l.qty + (b.dataset.line === '+' ? 1 : -1));
      renderCart();
    }));
  root.querySelectorAll('[data-line-val]').forEach(inp =>
    inp.addEventListener('change', () => {
      Cart.setQty(inp.dataset.lineVal, parseInt(inp.value, 10) || 0);
      renderCart();
    }));
  root.querySelector('[data-checkout]')?.addEventListener('click', checkout);
}

/* Checkout hands the cart to Zoho, which owns payment, tax, freight and the
   sales order.

   ⚠ THIS NO LONGER TALKS TO ZOHO DIRECTLY, AND IT CANNOT.
   Zoho's storefront API sends no CORS headers, so the previous version of this
   function — a loop of cross-origin POSTs — could never have run in a browser.
   It would have failed on the first request with "Failed to fetch". Verified
   7 Aug and re-verified 10 Aug against a preflight that returns 400 with no
   Access-Control-* headers at all.

   Everything now goes through our own /api/cart Pages Function, which makes the
   same calls server-to-server where CORS does not apply, then hands back a
   session cookie so Zoho's hosted checkout shows the customer their own cart.
   One request, one place errors can be reported from. */
async function checkout() {
  if (SOURCE.mode !== 'zoho') {
    alert('Checkout is not connected yet.\n\n' +
      'The shop, cart and freight all work. The ordering connection is built ' +
      'and tested but stays switched off until a full test order has been put ' +
      'through — that is the one remaining step.');
    return;
  }
  if (!Cart.lines.length) {
    alert('Your Nest is empty.');
    return;
  }
  /* Some SKUs on the approved price list have no Zoho record and so no
     product_variant_id — currently BD2382, which is unpriced and POA. Zoho
     cannot fulfil them. Fail loudly here rather than dropping a line silently
     and taking payment for an order that is short. */
  const orphan = Cart.lines.filter(l => !l.vid);
  if (orphan.length) {
    alert('One or more items in your Nest cannot be ordered online yet:\n\n' +
      orphan.map(l => `· ${l.name} — ${l.size} (${l.sku})`).join('\n') +
      '\n\nPlease email sales@thelittlenest.co.nz and we will sort it directly.');
    return;
  }

  const btn = document.querySelector('[data-checkout]');
  const restore = btn ? btn.textContent : null;
  if (btn) { btn.disabled = true; btn.textContent = 'Connecting…'; }

  try {
    const r = await fetch(PREFIX + 'api/cart', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      credentials: 'same-origin',
      body: JSON.stringify({
        items: Cart.lines.map(l => ({ vid: l.vid, qty: l.qty })),
      }),
    });
    const data = await r.json().catch(() => null);

    if (!r.ok || !data?.ok) {
      alert((data && data.message) ||
        'We could not start your order just now. Please try again in a moment, ' +
        'or email sales@thelittlenest.co.nz and we will complete it for you.');
      return;
    }
    /* Zoho owns the cart from here. The local Nest is deliberately NOT cleared:
       if the customer abandons checkout and comes back, their basket is still
       there. It is cleared on a confirmed order, not on a redirect. */
    location.href = data.checkout_url;
  } catch {
    alert('We could not reach our ordering system. Please check your connection ' +
      'and try again, or email sales@thelittlenest.co.nz.');
  } finally {
    if (btn) { btn.disabled = false; if (restore) btn.textContent = restore; }
  }
}

/* --- boot --------------------------------------------------------------- */

(async function init() {
  Cart.load();

  const product = document.querySelector('[data-product]');
  const tools   = document.querySelector('.shop-tools');
  const cart    = document.getElementById('cart-root');
  if (!product && !tools && !cart) return;   // an ordinary page, nothing to do

  try {
    await Catalogue.load();
  } catch (err) {
    console.error('[TLN] catalogue failed to load', err);
    return;   // static content stays on screen; only interactivity is lost
  }

  if (product) hydrateProduct(product);
  if (tools)   hydrateTools(tools);
  if (cart)    renderCart();
})();
