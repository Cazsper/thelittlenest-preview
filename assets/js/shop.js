function tile(p, prefix) {
  /* Same derivation as the generator: a product is POA only when EVERY size is,
     and the range is taken from the priced sizes. Must stay in step with
     price_label() in build-shop-pages.py or the hydrated grid will disagree with
     the static markup it replaces. */
  const ps = p.variants.filter(v => v.price != null).map(v => v.price);
  const price = !ps.length
    ? '<span class="shop-poa">Price on application</span>'
    : (Math.min(...ps) === Math.max(...ps)
        ? money(Math.min(...ps))
        : `${money(Math.min(...ps))} – ${money(Math.max(...ps))}`);
  return `<a class="shop-tile" href="${prefix}products/${esc(p.slug)}.html">
    ${phBlock(p, prefix, SIZES_TILE, 'shop-tile__ph', true)}
    <span class="shop-tile__name">${esc(p.name)}</span>
    <span class="shop-tile__price">${price}</span>
  </a>`;
}

function hydrateTools(tools) {
  const scope = tools.dataset.scope;
  const grid  = document.querySelector('[data-grid]');
  const count = tools.querySelector('[data-count]');
  /* Toolbar first, then the document. On CATEGORY pages the search input still
     lives inside `.shop-tools`; on shop.html it was moved out on 17 Aug 2026 to
     sit above the "Everything, A-Z" heading, so it is no longer a descendant of
     `tools`. Scoping to `tools` alone would have returned null there and the
     search box would have looked fine and filtered nothing. One page per
     layout, one selector that serves both. */
  const q     = tools.querySelector('[data-q]') || document.querySelector('[data-q]');
  const sort  = tools.querySelector('[data-sort]');
  if (!grid) return;

  /* shop.html only. Category pages name themselves with an <h1>. */
  const head  = document.querySelector('[data-grid-head]');

  // category pages sit one level down; shop.html is at the root
  const prefix = scope === 'all' ? '' : '../';

  const paint = () => {
    const term = (q?.value || '').trim().toLowerCase();
    let list = scope === 'all'
      ? Catalogue.all().slice()
      : Catalogue.inCat(Catalogue.cat(scope).name).slice();

    if (term) list = list.filter(p =>
      p.name.toLowerCase().includes(term) ||
      p.variants.some(v => (v.sku || '').toLowerCase().includes(term)));

    const s = sort?.value || 'featured';
    let html;
    if (s === 'featured') {
      /* The curated presentation, and the only sort with two blocks in it.
         The divider is SUPPRESSED WHILE SEARCHING: with a term typed the
         customer is not browsing a curated running order any more, and a
         "the rest of the range" rule inside four search results reads as a
         section break that means nothing. The order itself is kept, so a
         featured match still comes above an unfeatured one. */
      const { head: hd, tail } = arrange(list);
      /* BOTH SIDES, or no divider. ⚠ MIRRORS grid_html() in
         build-shop-pages.py. A separator with nothing above it is not a
         separator: a category page whose products are none of the featured
         ones opened with the words "The rest of the range" and then listed the
         whole category. Found on /categories/towels-bathrobes. */
      const showBreak = hd.length && tail.length && !term;
      html = hd.map(p => tile(p, prefix)).join('')
        + (showBreak
            ? `<h2 class="shop-grid__break">The rest of the range <span>${tail.length} product${tail.length === 1 ? '' : 's'}</span></h2>`
            : '')
        + tail.map(p => tile(p, prefix)).join('');
    } else {
      if (s === 'lo')      list.sort((a, b) => (a.lo == null) - (b.lo == null) || a.lo - b.lo);
      else if (s === 'hi') list.sort((a, b) => (a.hi == null) - (b.hi == null) || b.hi - a.hi);
      else                 list.sort((a, b) => a.name.localeCompare(b.name));
      html = list.map(p => tile(p, prefix)).join('');
    }

    grid.innerHTML = list.length
      ? html
      : '<p class="shop-empty">Nothing matches that search.</p>';
    if (count) count.textContent =
      list.length + (list.length === 1 ? ' product' : ' products');
    /* MIRRORS SHOP_HEADS in build-shop-pages.py. A grid sorted by price under a
       heading reading "Featured Products" is simply untrue about what is on
       screen, which is the whole reason "Everything, A-Z" survives as a label
       after ceasing to be the default. */
    if (head) head.textContent = term ? HEADS.search : (HEADS[s] || HEADS.featured);
  };

  q?.addEventListener('input', paint);
  sort?.addEventListener('change', paint);

  /* Repaint once on load IF the edge substituted something. The static markup
     is generated from the price list, so an override published through /admin
     (a renamed product, an uploaded photograph) is not in it. Without this the
     tile kept the built name and the striped "Photography to come" placeholder
     until the customer happened to search or sort, which is when paint() first
     ran. That was true from the day the Products CMS shipped.

     Guarded rather than unconditional: with nothing published this is every
     visitor paying an innerHTML of up to 173 tiles for an identical result.

     `Order.hasOverrides()` is the same guard for the same reason, one file
     along. The grid is generated in the BUILT running order, so a running order
     published through /admin is invisible until something repaints. Both flags
     are absent unless the edge actually substituted, so a site with nothing
     published still pays nothing. */
  if (Catalogue.hasOverrides() || Order.hasOverrides()) paint();

  /* The hero search proxy that used to live here was REMOVED on 17 Aug 2026.
     It was a second search field at the top of shop.html that mirrored its
     value into [data-q] and scrolled the customer down. Once the real field
     moved to sit directly above "Everything, A-Z" the proxy had nothing left to
     do: it existed only so customers could search without scrolling past the
     category cards, and the search now sits right below those cards anyway.
     Keeping it would have meant two inputs filtering one grid.
     See the note in build-shop-pages.py. */
}

/* --- cart page ---------------------------------------------------------- */

function renderCart() {
  const root = document.getElementById('cart-root');
  if (!root) return;

  if (!Cart.lines.length) {
    root.innerHTML = `
      <section class="container shop-head">
        <h1 class="serif">Your Nest is empty</h1>
        <p class="shop-head__lede">Nothing here yet.</p>
        <p><a class="btn" href="shop.html">Shop the range →</a></p>
      </section>`;
    return;
  }

  const sub = Cart.subtotal();
  const fr = freight(sub);
  root.innerHTML = `
  <section class="container shop-head"><h1 class="serif">Your Nest</h1></section>
  <section class="container shop-cart">
    <div class="shop-cart__lines">
      ${Cart.lines.map(l => `
        <div class="shop-line">
          ${phBlock(Catalogue.product(l.pid), '', SIZES_THUMB, 'shop-line__ph', false)}
          <div class="shop-line__body">
            <a class="shop-line__name" href="products/${esc(l.slug)}.html">${esc(l.name)}</a>
            <p class="shop-line__meta">${esc(l.size)} · SKU ${esc(l.sku)}</p>
            <button class="shop-line__rm" type="button" data-rm="${esc(l.key)}">Remove</button>
          </div>
          <div class="shop-qty shop-qty--sm">
            <button type="button" data-line="-" data-key="${esc(l.key)}" aria-label="Decrease">–</button>
            <input type="text" inputmode="numeric" value="${l.qty}" data-line-val="${esc(l.key)}" aria-label="Quantity">
            <button type="button" data-line="+" data-key="${esc(l.key)}" aria-label="Increase">+</button>
          </div>
          <span class="shop-line__price">${money(l.qty * l.price)}</span>
        </div>`).join('')}
    </div>
    <aside class="shop-sum">
      <h2 class="caps">Summary</h2>
      <p class="shop-sum__row"><span>Subtotal</span><span>${money(sub)}</span></p>
      <p class="shop-sum__row"><span>Freight</span><span>${fr === 0 ? 'Free' : money(fr)}</span></p>
      <p class="shop-sum__note">Rural delivery adds $9.00. Final freight is
        confirmed at checkout against your address.</p>
      <p class="shop-sum__total"><span>Total</span><span>${money(sub + fr)}</span></p>
      <button class="btn shop-checkout" type="button" data-checkout>Checkout →</button>
      <p class="shop-sum__note">GST inclusive. Payment is taken securely by Stripe.</p>
    </aside>
  </section>`;

  root.querySelectorAll('[data-rm]').forEach(b =>
    b.addEventListener('click', () => { Cart.remove(b.dataset.rm); renderCart(); }));
  root.querySelectorAll('[data-line]').forEach(b =>
    b.addEventListener('click', () => {
      const l = Cart.lines.find(x => x.key === b.dataset.key);
      if (!l) return;
      Cart.setQty(l.key, l.qty + (b.dataset.line === '+' ? 1 : -1));
      renderCart();
    }));
  root.querySelectorAll('[data-line-val]').forEach(inp =>
    inp.addEventListener('change', () => {
      /* AN UNREADABLE VALUE MUST NOT DELETE THE LINE.
         This was `parseInt(inp.value, 10) || 0`, and `|| 0` turned every
         unparseable entry into a removal: a customer who selected the quantity,
         deleted it to retype, and clicked away lost the item outright, with no
         confirmation and no undo. Typing "abc" emptied the whole Nest. Measured
         in a browser, not theorised.
         An explicit 0 still removes, because the "–" button reaches zero that
         way and that behaviour is intended. Anything unreadable is refused and
         the stored quantity is repainted, so the box returns to the truth. */
      const raw = inp.value.trim();
      if (!/^\d+$/.test(raw)) { renderCart(); return; }
      Cart.setQty(inp.dataset.lineVal, parseInt(raw, 10));
      renderCart();
    }));
  root.querySelector('[data-checkout]')?.addEventListener('click', checkout);
}

/* Checkout hands the cart to Zoho, which owns payment, tax, freight and the
   sales order.

   ⚠ THIS NO LONGER TALKS TO ZOHO DIRECTLY, AND IT CANNOT.
   Zoho's storefront API sends no CORS headers, so the previous version of this
   function · a loop of cross-origin POSTs · could never have run in a browser.
   It would have failed on the first request with "Failed to fetch". Verified
   7 Aug and re-verified 10 Aug against a preflight that returns 400 with no
   Access-Control-* headers at all.

   Everything now goes through our own /api/cart Pages Function, which makes the
   same calls server-to-server where CORS does not apply, then hands back a
   session cookie so Zoho's hosted checkout shows the customer their own cart.
   One request, one place errors can be reported from. */
async function checkout() {
  if (SOURCE.mode !== 'zoho') {
    alert('Checkout is not connected yet.\n\n' +
      'The shop, cart and freight all work. The ordering connection is built ' +
      'and tested but stays switched off until a full test order has been put ' +
      'through · that is the one remaining step.');
    return;
  }
  if (!Cart.lines.length) {
    alert('Your Nest is empty.');
    return;
  }
  /* Some SKUs on the approved price list have no Zoho record and so no
     product_variant_id · currently BD2382, which is unpriced and POA. Zoho
     cannot fulfil them. Fail loudly here rather than dropping a line silently
     and taking payment for an order that is short. */
  const orphan = Cart.lines.filter(l => !l.vid);
  if (orphan.length) {
    alert('One or more items in your Nest cannot be ordered online yet:\n\n' +
      orphan.map(l => `· ${l.name} · ${l.size} (${l.sku})`).join('\n') +
      '\n\nPlease email sales@thelittlenest.co.nz and we will sort it directly.');
    return;
  }

  const btn = document.querySelector('[data-checkout]');
  const restore = btn ? btn.textContent : null;
  if (btn) { btn.disabled = true; btn.textContent = 'Connecting…'; }

  try {
    const r = await fetch(PREFIX + 'api/cart', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      credentials: 'same-origin',
      body: JSON.stringify({
        items: Cart.lines.map(l => ({ vid: l.vid, qty: l.qty })),
      }),
    });
    const data = await r.json().catch(() => null);

    if (!r.ok || !data?.ok) {
      alert((data && data.message) ||
        'We could not start your order just now. Please try again in a moment, ' +
        'or email sales@thelittlenest.co.nz and we will complete it for you.');
      return;
    }
    /* Fired here, not on the button click above: this is the point past every
       validation (mode check, empty-cart check, orphan-SKU check) where the
       cart is genuinely about to leave for Zoho. Firing it earlier would
       count clicks that got rejected by one of those checks as real
       checkout starts. */
    document.dispatchEvent(new CustomEvent('tln:begin_checkout', { detail: {
      value: Cart.lines.reduce((sum, l) => sum + (l.price ?? 0) * l.qty, 0),
      items: Cart.lines.map(l => ({
        item_id: l.sku, item_name: l.name, item_variant: l.size,
        price: l.price ?? 0, quantity: l.qty,
      })),
    }}));
    /* Zoho owns the cart from here. The local Nest is deliberately NOT cleared:
       if the customer abandons checkout and comes back, their basket is still
       there. It is cleared on a confirmed order, not on a redirect. */
    location.href = data.checkout_url;
  } catch {
    alert('We could not reach our ordering system. Please check your connection ' +
      'and try again, or email sales@thelittlenest.co.nz.');
  } finally {
    if (btn) { btn.disabled = false; if (restore) btn.textContent = restore; }
  }
}

/* --- boot --------------------------------------------------------------- */

(async function init() {
  Cart.load();

  const product = document.querySelector('[data-product]');
  const tools   = document.querySelector('.shop-tools');
  const cart    = document.getElementById('cart-root');
  if (!product && !tools && !cart) return;   // an ordinary page, nothing to do

  try {
    /* In parallel, and only where the order is used. Order.load() never
       rejects: an unreadable order degrades to A to Z, whereas an unreadable
       catalogue costs the page its interactivity, so only one of these is
       allowed to abort the boot. */
    await Promise.all([Catalogue.load(), tools ? Order.load() : null]);
  } catch (err) {
    console.error('[TLN] catalogue failed to load', err);
    return;   // static content stays on screen; only interactivity is lost
  }

  if (product) hydrateProduct(product);
  if (tools)   hydrateTools(tools);
  if (cart)    renderCart();
})();
